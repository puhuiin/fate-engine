/** 四柱天干与地支藏干合并，用于核对调候用神是否到位 */
function collectGan(bazi: BaziResult): string[] {
  const out: string[] = [];
  for (const key of ['year', 'month', 'day', 'time'] as const) {
    const p = bazi.pillars[key];
    out.push(p.gan);
    if (Array.isArray(p.hideGan)) out.push(...p.hideGan);
  }
  return out;
}

export function buildTiaoHou(bazi: BaziResult): TiaoHouData {
  const day = bazi.dayMaster.gan;
  const month = bazi.pillars.month.zhi;
  const season = SEASON[month] ?? '四时';
  const use = TIAOHOU[day]?.[month] ?? [];

  const presentAll = collectGan(bazi);
  const usePresent = use.filter((u) => presentAll.includes(u));
  const useMissing = use.filter((u) => !presentAll.includes(u));
  const balanced = useMissing.length === 0;

  const principle =
    season !== '四时'
      ? `${day}日主生于${month}月，时值${season}季：${SEASON_PRINCIPLE[season]}`
      : `${day}日主调候信息不足，以五行生克通则参考。`;

  const summary =
    use.length > 0
      ? `${day}日主生于${month}月（${season}），穷通宝鉴取调候用神「${use.join('、')}」：${
          balanced
            ? '命局用神齐备，气候调和，先天调候条件较佳。'
            : `命局已见「${usePresent.join('、') || '无'}」，未现「${useMissing.join('、')}」；调候有所欠缺，宜靠后天环境与行运补足。`
        }`
      : `穷通宝鉴对${day}日主生于${month}月的调候记载不完整，暂以五行通则参考。`;

  return {
    day,
    month,
    monthNo: MONTH_ORDER[month] ?? 0,
    season,
    use,
    usePresent,
    useMissing,
    balanced,
    principle,
    summary,
    note: '调候用神关注「气候环境」：冬需火暖、夏需水润，与旺衰喜忌、格局用神并行参照，各司其职。',
  };
}
